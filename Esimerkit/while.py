# Ehdollinen toistorakenne! 

#  Alustetaan muuttujat / arvot
hinta = 5
kolikot = 0 

# Ehto on kirjoitettu toistolauseeseen

while kolikot < hinta: 
    # Tapa päivittää ehtoa
    kolikot += 1
    print("Annettu", kolikot, "kolikkoa.")

print("Kiitos, näkemiin!")

